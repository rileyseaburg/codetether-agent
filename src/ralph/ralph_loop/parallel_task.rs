//! Owned inputs retained by one spawned parallel story task.
use super::*;
pub(super) struct ParallelTask {
    pub(super) sem: Arc<tokio::sync::Semaphore>,
    pub(super) provider: Arc<dyn Provider>,
    pub(super) model: String,
    pub(super) prd_info: (String, String),
    pub(super) working_dir: PathBuf,
    pub(super) worktree_mgr: Option<Arc<WorktreeManager>>,
    pub(super) prebuilt_worktree: Option<crate::worktree::WorktreeInfo>,
    pub(super) progress_path: String,
    pub(super) ralph_tx: Option<mpsc::Sender<RalphEvent>>,
    pub(super) stage_learnings: Vec<String>,
    pub(super) bus: Option<Arc<AgentBus>>,
    pub(super) relay_enabled: bool,
    pub(super) relay_max_agents: usize,
    pub(super) relay_max_rounds: usize,
    pub(super) registry: Option<Arc<ProviderRegistry>>,
    pub(super) max_steps_per_story: usize,
    pub(super) max_quality_retries: usize,
    pub(super) max_rate_limit_retries: usize,
    pub(super) rate_limit_base_delay_ms: u64,
    pub(super) quality_checks_enabled: bool,
    pub(super) quality_checks: QualityChecks,
    pub(super) delegation: Option<DelegationState>,
    pub(super) story: UserStory,
}
