//! Forage objective seeding: moonshot.
use super::*;

/// Apply the seed moonshot okr policy to the supplied repository.
///
/// # Arguments
/// The repository owns persistence; a supplied rubric provides mission goals.
/// # Returns
/// The original seeding outcome, including the new objective ID where applicable.
/// # Errors
/// Returns repository lookup or persistence errors without replacing them.
/// # Examples
/// ```no_run
/// # async fn example(repo: &codetether_okr::OkrRepository) -> anyhow::Result<()> {
/// let _ = codetether_forage_core::seed::seed_moonshot_okr(repo, &Default::default()).await?;
/// # Ok(()) }
/// ```
pub async fn seed_moonshot_okr(repo: &OkrRepository, moonshots: &MoonshotRubric) -> Result<Uuid> {
    let mut okr = Okr::new(
        "Mission: Moonshot-Derived Autonomous Execution",
        format!(
            "Autogenerated forage objective derived from moonshots.\nMoonshots:\n- {}",
            moonshots.goals.join("\n- ")
        ),
    );
    okr.status = OkrStatus::Active;
    let okr_id = okr.id;

    let max_goals = 8usize;
    for (idx, goal) in moonshots.goals.iter().take(max_goals).enumerate() {
        let mut kr = KeyResult::new(
            okr_id,
            format!("Moonshot {}: {}", idx + 1, truncate_goal(goal, 96)),
            100.0,
            "%",
        );
        kr.description = goal.clone();
        okr.add_key_result(kr);
    }

    if okr.key_results.is_empty() {
        okr.add_key_result(KeyResult::new(
            okr_id,
            "Moonshot alignment delivered",
            100.0,
            "%",
        ));
    }

    let _ = repo.create_okr(okr).await?;
    tracing::info!(target: "codetether_agent::forage",
        okr_id = %okr_id,
        moonshot_count = moonshots.goals.len(),
        "Seeded moonshot-derived OKR for forage execution"
    );
    Ok(okr_id)
}
