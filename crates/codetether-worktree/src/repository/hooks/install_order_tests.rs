//! Install order between the `.githooks/` cache gate and `pre-commit`.
use super::install::install_with;
use crate::repository::publication::require_installed;
use std::path::Path;
use std::process::Command;

const POST_COMMIT: &str = "#!/bin/sh\n# repository post-commit\nexit 0\n";
const PRE_PUSH: &str = "#!/bin/sh\n# repository pre-push\nexit 0\n";
const CONFIG: &str = "default_install_hook_types: [pre-commit, post-commit]\nrepos: []\n";
const GENERATED: &str = "#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\n";

/// Mirrors the real installer: refuse a differing hook, else install both.
const GATE: &str = r#"set -eu
hooks="$(git rev-parse --path-format=absolute --git-path hooks)"
for n in post-commit pre-push; do
  d="$hooks/$n"
  if [ -e "$d" ] || [ -L "$d" ]; then
    if [ ! -L "$d" ] && cmp -s ".githooks/$n" "$d"; then continue; fi
    echo "Refusing to replace existing hook: $d" >&2; exit 1
  fi
done
mkdir -p "$hooks"
for n in post-commit pre-push; do
  [ -e "$hooks/$n" ] || install -m 755 ".githooks/$n" "$hooks/$n"
done
"#;

/// Fake `pre-commit`: records its arguments and writes each requested type.
const FAKE_PRE_COMMIT: &str = r#"#!/bin/sh
set -eu
echo "$*" >> "$(dirname "$0")/args.log"
hooks="$(git rev-parse --path-format=absolute --git-path hooks)"
mkdir -p "$hooks"
types=""; prev=""
for a in "$@"; do [ "$prev" = "--hook-type" ] && types="$types $a"; prev="$a"; done
[ -n "$types" ] || types="pre-commit post-commit"
for t in $types; do
  printf '#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\n' > "$hooks/$t"
  chmod 755 "$hooks/$t"
done
"#;

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().expect("parent")).expect("mkdir");
    std::fs::write(path, text).expect("write");
}

fn executable(path: &Path, text: &str) {
    write(path, text);
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o755)).expect("chmod");
    }
}

/// A repository like spotlessbinco, plus a fake `pre-commit` outside it.
fn gated_repo() -> (tempfile::TempDir, tempfile::TempDir, String) {
    let dir = tempfile::tempdir().expect("tempdir");
    assert!(
        Command::new("git")
            .args(["init", "-q"])
            .current_dir(dir.path())
            .status()
            .expect("git")
            .success()
    );
    write(&dir.path().join(".pre-commit-config.yaml"), CONFIG);
    write(&dir.path().join(".githooks/post-commit"), POST_COMMIT);
    write(&dir.path().join(".githooks/pre-push"), PRE_PUSH);
    write(
        &dir.path()
            .join("scripts/dev/install-pre-push-cache-gate.sh"),
        GATE,
    );
    let tools = tempfile::tempdir().expect("tools");
    let program = tools.path().join("pre-commit");
    executable(&program, FAKE_PRE_COMMIT);
    (dir, tools, program.display().to_string())
}

fn active(dir: &Path, name: &str) -> String {
    std::fs::read_to_string(dir.join(".git/hooks").join(name)).unwrap_or_default()
}

#[cfg(unix)]
#[tokio::test]
async fn gate_owns_post_commit_and_pre_commit_installs_only_its_type() {
    let (dir, tools, pre_commit) = gated_repo();
    let installed = install_with(dir.path(), &pre_commit)
        .await
        .expect("installs");
    assert_eq!(installed, ["pre-push", "pre-commit"]);
    assert_eq!(active(dir.path(), "post-commit"), POST_COMMIT);
    assert_eq!(active(dir.path(), "pre-push"), PRE_PUSH);
    assert!(active(dir.path(), "pre-commit").contains("File generated by pre-commit"));
    let args = std::fs::read_to_string(tools.path().join("args.log")).expect("args");
    assert_eq!(
        args.trim(),
        "install --install-hooks --hook-type pre-commit"
    );
    require_installed(dir.path())
        .await
        .expect("policy satisfied");
    install_with(dir.path(), &pre_commit)
        .await
        .expect("idempotent");
    assert_eq!(active(dir.path(), "post-commit"), POST_COMMIT);
}

#[cfg(unix)]
#[tokio::test]
async fn stale_generated_post_commit_is_replaced() {
    let (dir, _tools, pre_commit) = gated_repo();
    executable(&dir.path().join(".git/hooks/post-commit"), GENERATED);
    install_with(dir.path(), &pre_commit)
        .await
        .expect("replaces stale hook");
    assert_eq!(active(dir.path(), "post-commit"), POST_COMMIT);
    require_installed(dir.path())
        .await
        .expect("policy satisfied");
}

#[cfg(unix)]
#[tokio::test]
async fn custom_post_commit_is_still_refused() {
    let (dir, _tools, pre_commit) = gated_repo();
    let custom = "#!/bin/sh\n# operator hook\nexit 0\n";
    executable(&dir.path().join(".git/hooks/post-commit"), custom);
    let error = format!(
        "{:#}",
        install_with(dir.path(), &pre_commit).await.unwrap_err()
    );
    assert!(
        error.contains("Refusing to replace existing hook"),
        "{error}"
    );
    assert_eq!(active(dir.path(), "post-commit"), custom);
}

#[cfg(unix)]
#[tokio::test]
async fn without_githooks_pre_commit_runs_as_before() {
    let (dir, tools, pre_commit) = gated_repo();
    std::fs::remove_dir_all(dir.path().join(".githooks")).expect("rm .githooks");
    let installed = install_with(dir.path(), &pre_commit)
        .await
        .expect("installs");
    assert_eq!(installed, ["pre-commit"]);
    let args = std::fs::read_to_string(tools.path().join("args.log")).expect("args");
    assert_eq!(args.trim(), "install --install-hooks");
}
